public class Snowflake {
    float x;
    float y;
    float speed;
    float size;
    float sway;

    public Snowflake(float x, float y, float speed, float size, float sway) {
        this.x = x;
        this.y = y;
        this.speed = speed;
        this.size = size;
        this.sway = sway;
    }
}
